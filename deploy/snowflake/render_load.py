"""Render the Snowflake bronze load script from the local bronze manifest. Offline: connects to nothing.

    uv run python deploy/snowflake/render_load.py > /tmp/02_load_bronze.sql
    uv run python deploy/snowflake/render_load.py --since 2026-11-01 > /tmp/02_load_bronze.sql
    snow sql -f /tmp/02_load_bronze.sql        # PUT is client-side: run with the snow CLI or SnowSQL

Each (dataset, snapshot) is PUT under its own stage prefix (every bronze file is named part-0.parquet,
so a single prefix would overwrite all but one snapshot), then replaced in the landing table with a
delete + forced COPY. Rerunning the script for the same snapshots therefore never duplicates rows.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from ingestion.bronze import read_manifest  # noqa: E402
from ingestion.contract import DATASETS  # noqa: E402

DB = "airbnb"
LANDING = f"{DB}.bronze_landing"
STAGE = f"@{LANDING}.landing"


def sql_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def header() -> str:
    return f"""-- Generated by deploy/snowflake/render_load.py. Loads local bronze Parquet into Snowflake.
use role transformer;
use warehouse transforming;

create file format if not exists {LANDING}.parquet_ff type = parquet;
create file format if not exists {LANDING}.jsonl_ff type = json strip_outer_array = false;
create stage if not exists {LANDING}.landing;
"""


def create_landing_table(bronze: Path, dataset: str, first_snapshot: str) -> str:
    # The template is inferred from the oldest snapshot, so stage it first (PUT is idempotent).
    # IGNORE_CASE upper-cases inferred names. Without it, Parquet's lowercase names become quoted,
    # case-sensitive identifiers that unquoted dbt SQL (l.id) cannot resolve.
    put = load_snapshot(bronze, dataset, first_snapshot).strip().splitlines()[0]
    return f"""
{put}
create table if not exists {LANDING}.{dataset} using template (
  select array_agg(object_construct(*)) within group (order by order_id)
  from table(infer_schema(
    location => '{STAGE}/{dataset}/snapshot_date={first_snapshot}/',
    file_format => '{LANDING}.parquet_ff',
    ignore_case => true)));
create or replace view {DB}.bronze.{dataset} as
  select *, _snapshot_date as snapshot_date from {LANDING}.{dataset};
"""


def load_snapshot(bronze: Path, dataset: str, snapshot: str) -> str:
    local = (bronze / dataset / f"snapshot_date={snapshot}" / "part-0.parquet").as_posix()
    prefix = f"{STAGE}/{dataset}/snapshot_date={snapshot}/"
    return f"""
put {sql_str("file://" + local)} {prefix} auto_compress = false overwrite = true;
delete from {LANDING}.{dataset} where _snapshot_date = {sql_str(snapshot)}::date;
copy into {LANDING}.{dataset} from {prefix}
  file_format = (format_name = '{LANDING}.parquet_ff') match_by_column_name = case_insensitive force = true;
"""


def load_manifest(bronze: Path) -> str:
    local = (bronze / "_manifest.jsonl").as_posix()
    return f"""
put {sql_str("file://" + local)} {STAGE}/manifest/ auto_compress = false overwrite = true;
create or replace table {LANDING}.manifest (v variant);
copy into {LANDING}.manifest from {STAGE}/manifest/ file_format = (format_name = '{LANDING}.jsonl_ff') force = true;
create or replace view {DB}.bronze.manifest as
  select v:dataset::varchar            as dataset,
         v:snapshot_date::date         as snapshot_date,
         v:rows::bigint                as "rows",   -- reserved word: dbt reads it as adapter.quote('rows')
         v:status::varchar             as status,
         v:violations::array           as violations,
         v:file_sha256::varchar        as file_sha256,
         v:contract_sha256::varchar    as contract_sha256,
         v:ingested_at::timestamp_tz   as ingested_at
  from {LANDING}.manifest;
"""


def render(bronze: Path, since: str | None = None) -> str:
    entries = read_manifest(bronze / "_manifest.jsonl")
    if not entries:
        raise SystemExit(f"no bronze manifest at {bronze}: run `uv run python -m ingestion.bronze` first")
    parts = [header()]
    for dataset in DATASETS:
        snapshots = sorted(e["snapshot_date"] for e in entries if e["dataset"] == dataset)
        if not snapshots:
            continue
        selected = [s for s in snapshots if since is None or s >= since]
        parts.append(f"\n-- {dataset}: {len(selected)} of {len(snapshots)} snapshot(s)")
        parts.append(create_landing_table(bronze, dataset, snapshots[0]))
        parts.extend(load_snapshot(bronze, dataset, s) for s in selected)
    parts.append("\n-- Manifest: always reloaded in full (one small file).")
    parts.append(load_manifest(bronze))
    parts.append("\n-- Next: deploy/snowflake/03_verify_bronze.sql must return no rows.\n")
    return "".join(parts)


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--bronze", type=Path, default=ROOT / "data" / "bronze")
    p.add_argument("--since", help="only (re)load snapshots on or after this date (YYYY-MM-DD)")
    a = p.parse_args()
    sys.stdout.write(render(a.bronze.resolve(), a.since))


if __name__ == "__main__":
    main()
